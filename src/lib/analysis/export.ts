import { redact } from '@/lib/redact';
import type { AiExplanation } from '@/lib/ai/contract';
import { KIND_LABEL, LEVEL_LABEL, SUFFICIENCY_LABEL } from './report';
import type { Lang, Report } from './types';

/**
 * Exportable fraud report (JSON + print-to-PDF). Submitted content is redacted (cards, IBANs, Emirates ID,
 * OTPs, emails, phone digits). Intended to support a police / platform report; it is not an official document.
 */
export interface ExportBundle {
  schema: 'aman.fraud-report/v1';
  reportId: string;
  generatedAt: string;
  exportedAt: string;
  submittedContent: string;
  analysis: Omit<Report, 'target'> & { target: string };
  aiInterpretation?: { provider: string; model: string; summary: string; indicators: string[]; recommendations: string[] };
  disclaimer: string;
}

const DISCLAIMER =
  'Generated by AMAN AI (hackathon prototype). Risk scores come from deterministic rules; facts list their source and retrieval time; AI text is an interpretation only. This is not an official police, bank or government document.';

export function buildExport(r: Report, submitted: string, ai?: AiExplanation | null): ExportBundle {
  return {
    schema: 'aman.fraud-report/v1',
    reportId: r.id,
    generatedAt: r.generatedAt,
    exportedAt: new Date().toISOString(),
    submittedContent: redact(submitted).slice(0, 6000),
    analysis: { ...r, target: redact(r.target) },
    aiInterpretation: ai ? { provider: ai.provider, model: ai.model, summary: ai.summary.en, indicators: ai.indicators.map((x) => x.en), recommendations: ai.recommendations.map((x) => x.en) } : undefined,
    disclaimer: DISCLAIMER,
  };
}

export function downloadJson(bundle: ExportBundle) {
  const blob = new Blob([JSON.stringify(bundle, null, 2)], { type: 'application/json' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = `${bundle.reportId}.json`;
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    URL.revokeObjectURL(a.href);
    a.remove();
  }, 500);
}

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
const safeHref = (u: string) => (/^https?:\/\//i.test(u) ? esc(u) : '#');

/** Opens a print-ready report in a new window (user can "Save as PDF"). Screenshots are data URLs kept locally. */
export function printReport(r: Report, submitted: string, lang: Lang, ai?: AiExplanation | null, screenshots: string[] = []) {
  const ar = lang === 'ar';
  const t = (x: { en: string; ar: string }) => esc(x[lang]);
  const h = (en: string, a: string) => (ar ? a : en);
  const when = (iso: string) => new Date(iso).toLocaleString(ar ? 'ar-AE' : 'en-GB');
  const rows = (pairs: [string, string][]) => pairs.map(([k, v]) => `<tr><th>${k}</th><td>${v}</td></tr>`).join('');
  const html = `<!doctype html><html lang="${lang}" dir="${ar ? 'rtl' : 'ltr'}"><head><meta charset="utf-8"><title>${esc(r.id)} · AMAN AI</title>
<style>
body{font-family:'Segoe UI',Tahoma,Arial,sans-serif;color:#0f172a;margin:32px;font-size:13px;line-height:1.5}
h1{font-size:20px;margin:0}h2{font-size:14px;margin:22px 0 6px;border-bottom:1px solid #cbd5e1;padding-bottom:4px}
.meta{color:#475569;font-size:12px}.score{font-size:28px;font-weight:800}.pill{display:inline-block;padding:2px 8px;border-radius:999px;background:#f1f5f9;font-size:11px;font-weight:600}
table{width:100%;border-collapse:collapse}th,td{text-align:start;vertical-align:top;padding:4px 6px;border-bottom:1px solid #e2e8f0}th{width:28%;color:#475569;font-weight:600}
pre{white-space:pre-wrap;word-break:break-word;background:#f8fafc;border:1px solid #e2e8f0;padding:8px;border-radius:6px;font-size:12px}
.f{margin:6px 0;padding:6px 8px;border:1px solid #e2e8f0;border-radius:6px}.src{font-size:11px;color:#475569}
img{max-width:100%;max-height:420px;border:1px solid #cbd5e1;margin:6px 0}a{color:#047860;word-break:break-all}
footer{margin-top:24px;font-size:11px;color:#64748b;border-top:1px solid #cbd5e1;padding-top:8px}
</style></head><body>
<h1>AMAN AI · ${h('Fraud analysis report', 'تقرير تحليل احتيال')}</h1>
<div class="meta">${h('Report ID', 'رقم التقرير')}: <b>${esc(r.id)}</b> · ${h('Analysed', 'تاريخ التحليل')}: ${esc(when(r.generatedAt))} · ${t(KIND_LABEL[r.kind])}</div>
<p><span class="score">${r.score}/100</span> &nbsp; <b>${t(LEVEL_LABEL[r.level])}</b> &nbsp; <span class="pill">${t(SUFFICIENCY_LABEL[r.sufficiency])}</span></p>
<p>${t(r.summary)}</p>
<h2>${h('Submitted content (sensitive data redacted)', 'المحتوى المقدَّم (مع حجب البيانات الحساسة)')}</h2><pre>${esc(redact(submitted).slice(0, 6000))}</pre>
${r.official ? `<h2>${h('Official website comparison', 'المقارنة مع الموقع الرسمي')}</h2><table>${rows([[h('Organization', 'الجهة'), t(r.official.brand)], [h('Verified official domain(s)', 'النطاقات الرسمية الموثّقة'), esc(r.official.officialDomains.join(', '))], [h('Submitted domain', 'النطاق المقدَّم'), esc(r.official.submitted || '—')], [h('Match', 'مطابقة'), r.official.matches ? h('Yes', 'نعم') : h('No', 'لا')]])}</table>` : ''}
<h2>${h('Warning signs and findings', 'علامات التحذير والنتائج')}</h2>
${r.findings.map((f) => `<div class="f"><b>${t(f.title)}</b> <span class="pill">${esc(f.source ?? 'rule')}</span> <span class="pill">${f.weight > 0 ? '+' : ''}${f.weight}</span><br>${t(f.detail)}${f.evidence ? `<br><code>${esc(f.evidence)}</code>` : ''}</div>`).join('')}
${r.facts.length ? `<h2>${h('Verified technical facts', 'حقائق تقنية موثّقة')}</h2><table>${rows(r.facts.map((f) => [t(f.label), `${esc(f.value)}<div class="src">${esc(f.source)}${f.sourceUrl ? ` · <a href="${safeHref(f.sourceUrl)}">${esc(f.sourceUrl)}</a>` : ''} · ${esc(when(f.checkedAt))}</div>`]))}</table>` : ''}
${r.sources.length ? `<h2>${h('Public sources (retrieved)', 'مصادر علنية (تم جلبها)')}</h2>${r.sources.map((s) => `<div class="f"><b>${esc(s.title)}</b> <span class="pill">${esc(s.kind)}</span><br><a href="${safeHref(s.url)}">${esc(s.url)}</a><div class="src">${h('Retrieved', 'تاريخ الجلب')}: ${esc(when(s.retrievedAt))}</div></div>`).join('')}` : ''}
${ai ? `<h2>${h('AI interpretation', 'تفسير الذكاء الاصطناعي')} (${esc(ai.provider)} · ${esc(ai.model)})</h2><p>${t(ai.summary)}</p><ul>${ai.indicators.map((x) => `<li>${t(x)}</li>`).join('')}</ul>` : ''}
<h2>${h('Recommended actions', 'الإجراءات الموصى بها')}</h2><ul>${r.recommendations.map((x) => `<li>${t(x)}</li>`).join('')}</ul>
<h2>${h('Checks status', 'حالة الفحوصات')}</h2><table>${rows([...r.checks.map((c) => [t(c.label), `${esc(c.state)}${c.note ? ` · ${t(c.note)}` : ''}`] as [string, string]), ...r.unavailableChecks.map((u) => [t(u), h('not performed', 'لم يُنفَّذ')] as [string, string])])}</table>
${screenshots.length ? `<h2>${h('User-provided screenshots', 'لقطات شاشة قدّمها المستخدم')}</h2>${screenshots.map((s) => (s.startsWith('data:image/') ? `<img src="${esc(s)}" alt="">` : '')).join('')}` : ''}
<footer>${esc(DISCLAIMER)}</footer>
<script>window.onload=function(){setTimeout(function(){window.print()},300)}</script>
</body></html>`;
  const w = window.open('', '_blank');
  if (!w) return false;
  w.document.open();
  w.document.write(html);
  w.document.close();
  return true;
}
