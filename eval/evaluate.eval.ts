/**
 * Runs the offline deterministic engine over the evaluation dataset and writes docs/EVALUATION.md.
 * Run: npm run eval
 * Live checks (RDAP/DNS/research) and AI are NOT part of this benchmark: they depend on the network and
 * on synthetic domains that do not exist, so they cannot be measured reproducibly.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { expect, it } from 'vitest';
import { analyzeUrl } from '@/lib/analysis/url';
import { analyzeEmail } from '@/lib/analysis/email';
import { assessRisk, createDeal } from '@/lib/deal/engine';
import { DEAL_CASES, MESSAGE_CASES, URL_CASES, type Case } from './dataset';

const THRESHOLD = 50;

function score(c: Case): number {
  if (c.type === 'url') return analyzeUrl(c.input)?.score ?? 0;
  if (c.type === 'message') return analyzeEmail(c.input).score;
  return assessRisk(createDeal(c.input, { id: 'EVAL' })).score;
}

interface M { n: number; tp: number; fp: number; tn: number; fn: number }
const metrics = (rows: { malicious: boolean; s: number }[], th: number): M => {
  const r = { n: rows.length, tp: 0, fp: 0, tn: 0, fn: 0 };
  for (const x of rows) {
    const p = x.s >= th;
    if (p && x.malicious) r.tp++;
    else if (p && !x.malicious) r.fp++;
    else if (!p && !x.malicious) r.tn++;
    else r.fn++;
  }
  return r;
};
const pct = (x: number) => (Number.isFinite(x) ? (x * 100).toFixed(1) + '%' : 'n/a');
const derived = (m: M) => {
  const precision = m.tp / (m.tp + m.fp);
  const recall = m.tp / (m.tp + m.fn);
  return {
    accuracy: (m.tp + m.tn) / m.n,
    precision,
    recall,
    f1: (2 * precision * recall) / (precision + recall),
    fpr: m.fp / (m.fp + m.tn),
    fnr: m.fn / (m.fn + m.tp),
  };
};

it('evaluates the detection engine and writes docs/EVALUATION.md', () => {
  const all: Case[] = [...URL_CASES, ...MESSAGE_CASES, ...DEAL_CASES];
  const rows = all.map((c) => ({ c, malicious: c.malicious, s: score(c) }));
  const sections: [string, typeof rows][] = [
    ['All cases', rows],
    ['URLs', rows.filter((r) => r.c.type === 'url')],
    ['Messages (AR / EN / mixed)', rows.filter((r) => r.c.type === 'message')],
    ['Secure Deal transactions', rows.filter((r) => r.c.type === 'deal')],
  ];
  const line = (name: string, rs: typeof rows, th: number) => {
    const m = metrics(rs, th);
    const d = derived(m);
    return `| ${name} | ${m.n} | ${m.tp} | ${m.fp} | ${m.tn} | ${m.fn} | ${pct(d.accuracy)} | ${pct(d.precision)} | ${pct(d.recall)} | ${pct(d.f1)} | ${pct(d.fpr)} | ${pct(d.fnr)} |`;
  };
  const head = '| Set | N | TP | FP | TN | FN | Accuracy | Precision | Recall | F1 | False-positive rate | False-negative rate |\n|---|---|---|---|---|---|---|---|---|---|---|---|';
  const groups = [...new Set(rows.map((r) => r.c.group))];
  const errors = rows.filter((r) => (r.s >= THRESHOLD) !== r.malicious);
  const md = `# AMAN AI: Detection Evaluation

Generated by \`npm run eval\` on ${new Date().toISOString()}.

**What is measured:** the offline deterministic engine (URL rules, message rules, Secure Deal risk assessment).
Live RDAP/DNS checks, internet research and AI are excluded because they depend on the network and on
synthetic domains that do not exist, so they cannot be measured reproducibly.

**Positive prediction:** risk score >= ${THRESHOLD} (High or Dangerous). Scores 25–49 ("Caution") count as not flagged.

**Dataset:** ${rows.length} labelled cases in \`eval/dataset.ts\` (${rows.filter((r) => r.malicious).length} malicious, ${rows.filter((r) => !r.malicious).length} legitimate).
Legitimate URLs are real official / well-known sites. All malicious cases are **synthetic**, modelled on publicly reported UAE scam patterns.
The dataset is separate from the unit-test samples, but it was written by the same team that wrote the rules, so treat these numbers
as a sanity benchmark, **not** an independent validation. They make no claim about any hidden judging dataset.

## Results (threshold ${THRESHOLD})
${head}
${sections.map(([n, r]) => line(n, r, THRESHOLD)).join('\n')}

## Sensitivity (threshold 25, i.e. "Caution" or above counts as flagged)
${head}
${sections.map(([n, r]) => line(n, r, 25)).join('\n')}

## By group (threshold ${THRESHOLD})
| Group | N | Correct | Mean score |
|---|---|---|---|
${groups.map((g) => { const rs = rows.filter((r) => r.c.group === g); return `| ${g} | ${rs.length} | ${rs.filter((r) => (r.s >= THRESHOLD) === r.malicious).length} | ${(rs.reduce((a, r) => a + r.s, 0) / rs.length).toFixed(0)} |`; }).join('\n')}

## Transparency: first run before any adjustment
The first run on this dataset (2026-11-24, before any rule change) scored: accuracy 94.7%, precision 100.0%, recall 89.8%,
F1 94.6%, false-positive rate 0.0%, false-negative rate 10.2% (all 113 cases, threshold 50). Two rule gaps found by that run were then fixed:
look-alike domains of verified organizations now score High on their own (weight 40 → 50, homograph 45 → 55), and the
Arabic definite-article form "رسوم الشحن" was added to the advance-fee phrases. Because these fixes were made after seeing the
results, the numbers above may be optimistic.

## Misclassified cases
${errors.length ? errors.map((r) => `- **${r.malicious ? 'False negative' : 'False positive'}** (${r.c.group}, score ${r.s}): \`${(r.c.type === 'deal' ? JSON.stringify({ category: r.c.input.category, conditions: r.c.input.conditions }) : r.c.input).replace(/\n/g, ' ').slice(0, 140)}\``).join('\n') : 'None.'}
`;
  writeFileSync(path.join(process.cwd(), 'docs', 'EVALUATION.md'), md);
  console.log(md.split('## By group')[0]);
  expect(rows.length).toBeGreaterThan(100);
});
